//! Corpus metrics: what the maps recognise, what survives a round trip, what is lost.
//!
//! - **Coverage.** Sections and entries recognised by any of their template ids, and the
//!   resources the converted sections refer to; templates nothing recognised, by frequency.
//! - **Round trip CDA → FHIR → CDA.** The significant values of the document — codes (with
//!   their code system), identifiers, timestamps at their precision, quantities, name and
//!   address parts — before and after, compared as multisets. Only the header and the sections
//!   the maps recognise count: an unrecognised section loses its entries by design, and coverage
//!   reports it.
//! - **Losses.** Everything the conversion reported, per document.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use serde_json::{Value, json};

use crate::report::{Coverage, sections, statement};
use crate::{CLINICAL_DOCUMENT, Converter, Options};

/// Codes that only say what kind of act something is; regenerated by the maps, not content.
const STRUCTURAL_CODE_SYSTEMS: &[&str] = &[
    "2.16.840.1.113883.5.4",  // ActCode (ASSERTION, CONC, …)
    "2.16.840.1.113883.5.6",  // ActClass
    "2.16.840.1.113883.5.25", // Confidentiality
];

/// The measurements of one document.
#[derive(Debug, Clone, Default)]
pub struct DocumentMetrics {
    pub path: PathBuf,
    /// The document is a fragment wrapped in a minimal document.
    pub fragment: bool,
    pub error: Option<String>,
    pub coverage: Coverage,
    pub losses: usize,
    pub losses_by_stage: BTreeMap<String, usize>,
    /// Significant values before, and how many came back after CDA → FHIR → CDA.
    pub facts: usize,
    pub kept: usize,
    /// Values that did not come back, for the report.
    pub missing: Vec<String>,
    pub resources: BTreeMap<String, usize>,
    /// FHIR → CDA → FHIR: significant values of the resources (the Composition aside) before,
    /// and how many came back.
    pub fhir_facts: usize,
    pub fhir_kept: usize,
    /// US Core validity of the converted resources, when a validator was given.
    pub validity: Option<crate::validation::Validity>,
    /// C-CDA conformance of the document converted back, when a validator was given.
    pub cda_validity: Option<crate::cda_validation::CdaValidity>,
}

/// Validators for the converted output.
#[derive(Default)]
pub struct Validators<'a> {
    pub us_core: Option<&'a crate::validation::Validator>,
    pub ccda: Option<&'a crate::cda_validation::CdaValidator>,
}

/// Converts a document there and back and measures it.
pub async fn measure(converter: &Converter, path: &Path, xml: &str) -> DocumentMetrics {
    measure_with(converter, path, xml, &Validators::default()).await
}

/// [`measure`], validating the resources against US Core as well.
pub async fn measure_with(
    converter: &Converter,
    path: &Path,
    xml: &str,
    validators: &Validators<'_>,
) -> DocumentMetrics {
    let mut metrics = DocumentMetrics {
        path: path.to_owned(),
        ..DocumentMetrics::default()
    };
    let options = Options {
        deterministic_ids: true,
    };
    let (xml, fragment) = match as_document(xml) {
        Some(wrapped) => (wrapped, true),
        None if is_document(xml) => (xml.to_owned(), false),
        None => {
            metrics.error = Some("skipped: neither a document nor a section".to_owned());
            return metrics;
        }
    };
    metrics.fragment = fragment;
    let to_fhir = match converter.to_fhir(&xml, &options).await {
        Ok(result) => result,
        Err(error) => {
            metrics.error = Some(format!("to FHIR: {error}"));
            return metrics;
        }
    };
    metrics.coverage = to_fhir.report.coverage.clone();
    count_losses(&mut metrics, &to_fhir.report.losses);
    for entry in to_fhir.bundle["entry"].as_array().into_iter().flatten() {
        if let Some(kind) = entry["resource"]["resourceType"].as_str() {
            *metrics.resources.entry(kind.to_owned()).or_default() += 1;
        }
    }
    if let Some(validator) = validators.us_core {
        metrics.validity = Some(validator.validate_bundle(&to_fhir.bundle).await);
    }
    let to_cda = match converter.to_cda(&to_fhir.bundle, &options).await {
        Ok(result) => result,
        Err(error) => {
            metrics.error = Some(format!("back to CDA: {error}"));
            return metrics;
        }
    };
    count_losses(&mut metrics, &to_cda.report.losses);
    let before = match fml_xml::read(&xml, converter.model(), Some(CLINICAL_DOCUMENT)) {
        Ok(document) => document.json,
        Err(error) => {
            metrics.error = Some(format!("reading: {error}"));
            return metrics;
        }
    };
    let after = match fml_xml::read(&to_cda.xml, converter.model(), Some(CLINICAL_DOCUMENT)) {
        Ok(document) => document.json,
        Err(error) => {
            metrics.error = Some(format!("reading the result: {error}"));
            return metrics;
        }
    };
    if let Some(validator) = validators.ccda {
        metrics.cda_validity = Some(validator.validate(&after).await);
    }
    // FHIR → CDA → FHIR: the resources of the first conversion against those of the second.
    if let Ok(again) = converter.to_fhir(&to_cda.xml, &options).await {
        let first = bundle_facts(&to_fhir.bundle);
        let mut second = bundle_facts(&again.bundle);
        for (fact, count) in &first {
            metrics.fhir_facts += count;
            if let Some(n) = second.get_mut(fact) {
                let taken = (*n).min(*count);
                *n -= taken;
                metrics.fhir_kept += taken;
            }
        }
    }
    let supported = converter.supported_templates();
    let expected = cda_facts(&before, supported, fragment);
    let mut found = cda_facts(&after, supported, fragment);
    for (fact, count) in &expected {
        metrics.facts += count;
        let available = found.get_mut(fact).map_or(0, |n| {
            let taken = (*n).min(*count);
            *n -= taken;
            taken
        });
        metrics.kept += available;
        if available < *count {
            metrics.missing.push(fact.clone());
        }
    }
    metrics
}

fn count_losses(metrics: &mut DocumentMetrics, losses: &[crate::Loss]) {
    metrics.losses += losses.len();
    for loss in losses {
        *metrics
            .losses_by_stage
            .entry(loss.stage.name().to_owned())
            .or_default() += 1;
    }
}

/// The significant values of a Bundle's resources, the Composition and generated ids aside.
fn bundle_facts(bundle: &Value) -> BTreeMap<String, usize> {
    let mut out = BTreeMap::new();
    for entry in bundle["entry"].as_array().into_iter().flatten() {
        let resource = &entry["resource"];
        let kind = resource["resourceType"].as_str().unwrap_or_default();
        if kind == "Composition" {
            continue;
        }
        for fact in fhir_facts(resource) {
            *out.entry(format!("{kind} {fact}")).or_default() += 1;
        }
    }
    out
}

/// A section fragment (`section`, or a `component` holding one) wrapped in a minimal document;
/// `None` for a document. The namespace declarations fragments leave out are added.
pub fn as_document(xml: &str) -> Option<String> {
    let body = match xml.find("<?xml") {
        Some(start) => {
            let end = xml[start..].find("?>").map_or(start, |e| start + e + 2);
            &xml[end..]
        }
        None => xml,
    };
    let trimmed = strip_comments(body);
    let root = root_name(&trimmed)?;
    let section = match root.as_str() {
        "ClinicalDocument" => return None,
        "section" => trimmed.trim().to_owned(),
        "component" => {
            let start = trimmed.find("<section")?;
            let end = trimmed.rfind("</section>")? + "</section>".len();
            trimmed[start..end].to_owned()
        }
        _ => return None,
    };
    // The namespaces of the section stay on it; the wrapper declares those it leaves out.
    let section = section.replacen(
        "<section",
        "<section xmlns=\"urn:hl7-org:v3\" xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\" xmlns:sdtc=\"urn:hl7-org:sdtc\"",
        1,
    );
    let section = dedupe_namespaces(&section);
    Some(format!(
        r#"<ClinicalDocument xmlns="urn:hl7-org:v3" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns:sdtc="urn:hl7-org:sdtc">
  <realmCode code="US"/>
  <typeId root="2.16.840.1.113883.1.3" extension="POCD_HD000040"/>
  <templateId root="2.16.840.1.113883.10.20.22.1.1" extension="2015-08-01"/>
  <id root="2.16.840.1.113883.19.5.99999.1" extension="fragment"/>
  <code code="34109-9" codeSystem="2.16.840.1.113883.6.1" displayName="Note"/>
  <title>Fragment</title>
  <effectiveTime value="20200101"/>
  <confidentialityCode code="N" codeSystem="2.16.840.1.113883.5.25"/>
  <recordTarget><patientRole><id root="2.16.840.1.113883.19.5.99999.2" extension="1"/><patient><name><given>Test</given><family>Patient</family></name><administrativeGenderCode code="F" codeSystem="2.16.840.1.113883.5.1"/><birthTime value="19700101"/></patient></patientRole></recordTarget>
  <author><time value="20200101"/><assignedAuthor><id root="2.16.840.1.113883.4.6" extension="1"/><assignedPerson><name><given>Test</given><family>Author</family></name></assignedPerson></assignedAuthor></author>
  <custodian><assignedCustodian><representedCustodianOrganization><id root="2.16.840.1.113883.19.5.99999.3"/><name>Test</name></representedCustodianOrganization></assignedCustodian></custodian>
  <component><structuredBody><component>{section}</component></structuredBody></component>
</ClinicalDocument>"#
    ))
}

/// Whether the first element is a ClinicalDocument.
fn is_document(xml: &str) -> bool {
    let body = strip_comments(match xml.find("?>") {
        Some(end) if xml.trim_start().starts_with("<?xml") => &xml[end + 2..],
        _ => xml,
    });
    root_name(&body).as_deref() == Some("ClinicalDocument")
}

fn strip_comments(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(start) = rest.find("<!--") {
        out.push_str(&rest[..start]);
        match rest[start..].find("-->") {
            Some(end) => rest = &rest[start + end + 3..],
            None => return out,
        }
    }
    out.push_str(rest);
    out
}

fn root_name(text: &str) -> Option<String> {
    let mut rest = text;
    loop {
        let start = rest.find('<')?;
        rest = &rest[start + 1..];
        // Processing instructions (`<?xml-stylesheet …?>`) and declarations come before it.
        if rest.starts_with('?') || rest.starts_with('!') {
            continue;
        }
        let name: String = rest
            .chars()
            .take_while(|c| !c.is_whitespace() && *c != '>' && *c != '/')
            .collect();
        return Some(name.rsplit(':').next().unwrap_or(&name).to_owned());
    }
}

/// Drops a namespace declaration the section's own start tag repeats.
fn dedupe_namespaces(section: &str) -> String {
    let Some(end) = section.find('>') else {
        return section.to_owned();
    };
    let (tag, rest) = section.split_at(end);
    let mut seen = std::collections::HashSet::new();
    let mut out = String::new();
    for part in tag.split(' ') {
        let name = part.split('=').next().unwrap_or(part);
        if name.starts_with("xmlns") && !seen.insert(name.to_owned()) {
            continue;
        }
        if !out.is_empty() {
            out.push(' ');
        }
        out.push_str(part);
    }
    out + rest
}

/// The significant values of a document, as a multiset: the header (patient, authors,
/// custodian) and the recognised sections' entries.
pub fn cda_facts(
    document: &Value,
    supported: &std::collections::HashSet<String>,
    fragment: bool,
) -> BTreeMap<String, usize> {
    let mut facts = BTreeMap::new();
    if !fragment {
        for key in ["recordTarget", "author", "custodian", "legalAuthenticator"] {
            collect(&document[key], key, &mut facts);
        }
        collect(&document["code"], "code", &mut facts);
        collect(&document["effectiveTime"], "effectiveTime", &mut facts);
    }
    for section in sections(document) {
        let recognised = section["templateId"]
            .as_array()
            .into_iter()
            .flatten()
            .filter_map(|t| t["root"].as_str())
            .any(|root| supported.contains(root));
        if !recognised {
            continue;
        }
        collect(&section["code"], "section", &mut facts);
        for entry in section["entry"].as_array().into_iter().flatten() {
            if let Some(statement) = statement(entry) {
                collect(statement, "entry", &mut facts);
            }
        }
    }
    facts
}

fn collect(value: &Value, context: &str, facts: &mut BTreeMap<String, usize>) {
    match value {
        Value::Object(object) => {
            for (key, child) in object {
                match key.as_str() {
                    "templateId" | "typeId" | "realmCode" | "text" | "reference" => continue,
                    _ => {}
                }
                collect(child, key, facts);
            }
            let mut add = |fact: String| *facts.entry(fact).or_default() += 1;
            // A coded value.
            if let (Some(code), Some(system)) = (
                object.get("code").and_then(Value::as_str),
                object.get("codeSystem").and_then(Value::as_str),
            ) && !STRUCTURAL_CODE_SYSTEMS.contains(&system)
            {
                add(format!("code {system}|{code}"));
            }
            // An identifier.
            if let Some(root) = object.get("root").and_then(Value::as_str)
                && context != "templateId"
            {
                let extension = object
                    .get("extension")
                    .and_then(Value::as_str)
                    .unwrap_or("");
                add(format!("id {}|{extension}", root.to_ascii_uppercase()));
            }
            // A timestamp, at its precision.
            if let Some(time) = object.get("value").and_then(Value::as_str)
                && looks_like_time(time)
                && matches!(
                    context,
                    "effectiveTime"
                        | "low"
                        | "high"
                        | "time"
                        | "birthTime"
                        | "sdtcDeceasedTime"
                        | "center"
                )
            {
                add(format!("time {time}"));
            }
            // A quantity.
            if let Some(number) = object.get("value").filter(|v| v.is_number()) {
                let unit = object.get("unit").and_then(Value::as_str).unwrap_or("1");
                add(format!("quantity {number} {unit}"));
            }
            // A name or address part.
            if matches!(
                context,
                "given"
                    | "family"
                    | "prefix"
                    | "suffix"
                    | "streetAddressLine"
                    | "city"
                    | "state"
                    | "postalCode"
                    | "country"
            ) && let Some(text) = object.get("xmlText").and_then(Value::as_str)
            {
                add(format!("{context} {}", text.trim()));
            }
        }
        Value::Array(items) => {
            for item in items {
                collect(item, context, facts);
            }
        }
        _ => {}
    }
}

fn looks_like_time(text: &str) -> bool {
    text.len() >= 4 && text.as_bytes()[..4].iter().all(u8::is_ascii_digit)
}

/// The XML files of a list of files and folders.
pub fn corpus_files(inputs: &[PathBuf]) -> Vec<PathBuf> {
    fn walk(path: &Path, out: &mut Vec<PathBuf>) {
        if path.is_dir() {
            let Ok(entries) = std::fs::read_dir(path) else {
                return;
            };
            let mut entries: Vec<PathBuf> = entries.flatten().map(|e| e.path()).collect();
            entries.sort();
            for entry in entries {
                walk(&entry, out);
            }
        } else if path
            .extension()
            .is_some_and(|e| e.eq_ignore_ascii_case("xml"))
        {
            out.push(path.to_owned());
        }
    }
    let mut out = Vec::new();
    for input in inputs {
        walk(input, &mut out);
    }
    out
}

/// Totals over a corpus.
#[derive(Debug, Clone, Default)]
pub struct Summary {
    pub documents: usize,
    pub fragments: usize,
    pub failed: usize,
    pub sections: usize,
    pub recognised_sections: usize,
    pub entries: usize,
    pub recognised_entries: usize,
    pub resources: BTreeMap<String, usize>,
    pub facts: usize,
    pub kept: usize,
    pub fhir_facts: usize,
    pub fhir_kept: usize,
    pub losses: usize,
    pub losses_by_stage: BTreeMap<String, usize>,
    pub unknown_templates: BTreeMap<String, usize>,
    pub missing: BTreeMap<String, usize>,
    pub validity: Option<crate::validation::Validity>,
    pub cda_validity: Option<crate::cda_validation::CdaValidity>,
    /// Documents that are not well-formed XML (in the source).
    pub malformed: usize,
    /// Files that are neither a document nor a section (header fragments, single entries).
    pub skipped: usize,
}

pub fn summarize(all: &[DocumentMetrics]) -> Summary {
    let mut summary = Summary::default();
    for metrics in all {
        summary.documents += 1;
        if metrics.fragment {
            summary.fragments += 1;
        }
        if let Some(error) = &metrics.error {
            if error.starts_with("skipped") {
                summary.skipped += 1;
                summary.documents -= 1;
            } else if error.contains("not well-formed") {
                summary.malformed += 1;
            } else {
                summary.failed += 1;
            }
            continue;
        }
        if let Some(validity) = &metrics.validity {
            summary
                .validity
                .get_or_insert_with(Default::default)
                .add(validity);
        }
        if let Some(validity) = &metrics.cda_validity {
            summary
                .cda_validity
                .get_or_insert_with(Default::default)
                .add(validity);
        }
        summary.sections += metrics.coverage.sections.len();
        summary.recognised_sections += metrics
            .coverage
            .sections
            .iter()
            .filter(|s| s.recognised)
            .count();
        summary.entries += metrics.coverage.entries();
        summary.recognised_entries += metrics.coverage.recognised_entries();
        for (kind, count) in &metrics.resources {
            *summary.resources.entry(kind.clone()).or_default() += count;
        }
        summary.facts += metrics.facts;
        summary.kept += metrics.kept;
        summary.fhir_facts += metrics.fhir_facts;
        summary.fhir_kept += metrics.fhir_kept;
        summary.losses += metrics.losses;
        for (stage, count) in &metrics.losses_by_stage {
            *summary.losses_by_stage.entry(stage.clone()).or_default() += count;
        }
        for (template, count) in &metrics.coverage.unknown_templates {
            *summary
                .unknown_templates
                .entry(template.clone())
                .or_default() += count;
        }
        for fact in &metrics.missing {
            let kind = fact.split(' ').next().unwrap_or(fact).to_owned();
            *summary.missing.entry(kind).or_default() += 1;
        }
    }
    summary
}

fn percent(part: usize, whole: usize) -> String {
    if whole == 0 {
        "—".to_owned()
    } else {
        format!("{:.1}%", 100.0 * part as f64 / whole as f64)
    }
}

/// The corpus report in Markdown.
pub fn markdown(summary: &Summary, all: &[DocumentMetrics], root: Option<&Path>) -> String {
    use std::fmt::Write;
    let mut out = String::new();
    let _ = writeln!(out, "# Corpus report\n");
    let _ = writeln!(
        out,
        "{} documents ({} section fragments in a minimal document); {} not well-formed XML in the source, {} failed; {} other fragments skipped.\n",
        summary.documents, summary.fragments, summary.malformed, summary.failed, summary.skipped
    );
    let _ = writeln!(out, "| Measure | Value |\n|---|---|");
    let _ = writeln!(
        out,
        "| Sections recognised | {} of {} ({}) |",
        summary.recognised_sections,
        summary.sections,
        percent(summary.recognised_sections, summary.sections)
    );
    let _ = writeln!(
        out,
        "| Entries recognised | {} of {} ({}) |",
        summary.recognised_entries,
        summary.entries,
        percent(summary.recognised_entries, summary.entries)
    );
    let _ = writeln!(
        out,
        "| Round trip CDA → FHIR → CDA, significant values kept | {} of {} ({}) |",
        summary.kept,
        summary.facts,
        percent(summary.kept, summary.facts)
    );
    let _ = writeln!(
        out,
        "| Round trip FHIR → CDA → FHIR, significant values of the resources kept | {} of {} ({}) |",
        summary.fhir_kept,
        summary.fhir_facts,
        percent(summary.fhir_kept, summary.fhir_facts)
    );
    if let Some(validity) = &summary.validity {
        let _ = writeln!(
            out,
            "| Resources valid against US Core 6.1.0 | {} of {} ({}) |",
            validity.valid,
            validity.resources,
            percent(validity.valid, validity.resources)
        );
    }
    if let Some(validity) = &summary.cda_validity {
        let _ = writeln!(
            out,
            "| CDA written back conforming to C-CDA 5.0.0 templates | {} of {} documents ({}); {} of {} templated elements ({}) |",
            validity.valid,
            validity.documents,
            percent(validity.valid, validity.documents),
            validity.valid_elements,
            validity.elements,
            percent(validity.valid_elements, validity.elements)
        );
    }
    let _ = writeln!(out, "| Losses reported | {} |", summary.losses);
    let _ = writeln!(out, "\n## Resources\n\n| Type | Count |\n|---|---|");
    for (kind, count) in &summary.resources {
        let _ = writeln!(out, "| {kind} | {count} |");
    }
    if let Some(validity) = &summary.validity {
        let mut errors: Vec<(&String, &usize)> = validity.errors.iter().collect();
        errors.sort_by(|a, b| b.1.cmp(a.1).then(a.0.cmp(b.0)));
        let _ = writeln!(
            out,
            "\n## US Core validation errors\n\n| Error | Count |\n|---|---|"
        );
        for (message, count) in errors.iter().take(30) {
            let _ = writeln!(out, "| {} | {count} |", message.replace('|', "\\|"));
        }
    }
    if let Some(validity) = &summary.cda_validity {
        let mut errors: Vec<(&String, &usize)> = validity.errors.iter().collect();
        errors.sort_by(|a, b| b.1.cmp(a.1).then(a.0.cmp(b.0)));
        let _ = writeln!(
            out,
            "\n## C-CDA conformance errors (CDA written back)\n\nChecked: element cardinality, fixed and pattern values, error invariants of the templates applied by template id. Not checked: slices, terminology.\n\n| Error | Count |\n|---|---|"
        );
        for (message, count) in errors.iter().take(30) {
            let _ = writeln!(out, "| {} | {count} |", message.replace('|', "\\|"));
        }
        if !validity.unevaluated.is_empty() {
            let _ = writeln!(
                out,
                "\nInvariants that did not evaluate: {}",
                validity
                    .unevaluated
                    .iter()
                    .map(|(k, v)| format!("{k} ({v})"))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
        }
    }
    let _ = writeln!(out, "\n## Losses by stage\n\n| Stage | Count |\n|---|---|");
    for (stage, count) in &summary.losses_by_stage {
        let _ = writeln!(out, "| {stage} | {count} |");
    }
    let _ = writeln!(
        out,
        "\n## Values a round trip lost, by kind\n\n| Kind | Documents |\n|---|---|"
    );
    for (kind, count) in &summary.missing {
        let _ = writeln!(out, "| {kind} | {count} |");
    }
    let mut unknown: Vec<(&String, &usize)> = summary.unknown_templates.iter().collect();
    unknown.sort_by(|a, b| b.1.cmp(a.1).then(a.0.cmp(b.0)));
    let _ = writeln!(
        out,
        "\n## Templates not mapped\n\n| Template | Occurrences |\n|---|---|"
    );
    for (template, count) in unknown.iter().take(60) {
        let _ = writeln!(out, "| {template} | {count} |");
    }
    let _ = writeln!(
        out,
        "\n## Documents\n\n| Document | Sections | Entries | Round trip | Losses |\n|---|---|---|---|---|"
    );
    for metrics in all {
        let name = match root {
            Some(root) => metrics.path.strip_prefix(root).unwrap_or(&metrics.path),
            None => &metrics.path,
        };
        let name = name.display().to_string().replace('|', "\\|");
        match &metrics.error {
            Some(error) => {
                let _ = writeln!(
                    out,
                    "| {name} | — | — | — | error: {} |",
                    error.replace('|', "\\|")
                );
            }
            None => {
                let recognised = metrics
                    .coverage
                    .sections
                    .iter()
                    .filter(|s| s.recognised)
                    .count();
                let _ = writeln!(
                    out,
                    "| {name} | {recognised}/{} | {}/{} | {} | {} |",
                    metrics.coverage.sections.len(),
                    metrics.coverage.recognised_entries(),
                    metrics.coverage.entries(),
                    percent(metrics.kept, metrics.facts),
                    metrics.losses
                );
            }
        }
    }
    out
}

