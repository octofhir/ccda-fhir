/// How one recommended (consensus) resource of C-CDA on FHIR compares with ours.
#[derive(Debug, Clone)]
pub struct ConsensusResult {
    pub file: String,
    pub resource_type: String,
    /// Significant values of the recommended resource.
    pub facts: usize,
    /// How many of them our best matching resource of the type has.
    pub matched: usize,
    pub missing: Vec<String>,
}

/// Compares our conversion of the shared input CCD of `HL7/ccda-on-fhir`
/// (`mappings/examples/CDAtoFHIRExamples`) with the recommended outputs (`Rec_Output`): for each
/// recommended resource, the share of its significant values — codings, identifiers, dates,
/// quantities, coded and status fields — that our closest resource of the same type has.
pub async fn consensus(
    converter: &Converter,
    examples: &Path,
) -> Result<Vec<ConsensusResult>, String> {
    let input_dir = examples.join("Input");
    let input = std::fs::read_dir(&input_dir)
        .map_err(|e| format!("{}: {e}", input_dir.display()))?
        .flatten()
        .map(|e| e.path())
        .find(|p| p.extension().is_some_and(|e| e == "xml"))
        .ok_or("no input CCD")?;
    let xml = std::fs::read_to_string(&input).map_err(|e| e.to_string())?;
    let ours = converter
        .to_fhir(
            &xml,
            &Options {
                deterministic_ids: true,
            },
        )
        .await
        .map_err(|e| e.to_string())?
        .bundle;
    let mut files: Vec<PathBuf> = std::fs::read_dir(examples.join("Rec_Output"))
        .map_err(|e| e.to_string())?
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|e| e == "json" || e == "jsonc"))
        .collect();
    files.sort();
    let mut results = Vec::new();
    for file in files {
        let text = std::fs::read_to_string(&file).map_err(|e| e.to_string())?;
        let cleaned: String = text
            .lines()
            .filter(|line| !line.trim_start().starts_with("//"))
            .collect::<Vec<_>>()
            .join("\n");
        let Ok(json) = serde_json::from_str::<Value>(&cleaned) else {
            continue;
        };
        let recommended: Vec<&Value> = match &json {
            Value::Array(items) => items
                .iter()
                .map(|i| {
                    if i["resource"].is_object() {
                        &i["resource"]
                    } else {
                        i
                    }
                })
                .collect(),
            object if object["resource"].is_object() => vec![&object["resource"]],
            object => vec![object],
        };
        for resource in recommended {
            let Some(kind) = resource["resourceType"].as_str() else {
                continue;
            };
            let expected = fhir_facts(resource);
            let best = ours["entry"]
                .as_array()
                .into_iter()
                .flatten()
                .map(|e| &e["resource"])
                .filter(|r| r["resourceType"] == kind)
                .map(|r| {
                    let found = fhir_facts(r);
                    let matched = expected.iter().filter(|f| found.contains(*f)).count();
                    (matched, found)
                })
                .max_by_key(|(matched, _)| *matched);
            let (matched, found) = best.unwrap_or_default();
            results.push(ConsensusResult {
                file: file
                    .file_name()
                    .unwrap_or_default()
                    .to_string_lossy()
                    .into_owned(),
                resource_type: kind.to_owned(),
                facts: expected.len(),
                matched,
                missing: expected
                    .into_iter()
                    .filter(|f| !found.contains(f))
                    .collect(),
            });
        }
    }
    Ok(results)
}

/// The significant values of a FHIR resource, as a set: codings, identifiers, dates (normalised
/// to the precision written), quantities, and the code-valued fields that say what or in what
/// state (status, intent, category, gender, …). References and narrative do not count.
pub fn fhir_facts(resource: &Value) -> std::collections::BTreeSet<String> {
    fn walk(value: &Value, key: &str, out: &mut std::collections::BTreeSet<String>) {
        match value {
            Value::Object(object) => {
                if let (Some(system), Some(code)) = (
                    object.get("system").and_then(Value::as_str),
                    object.get("code").and_then(Value::as_str),
                ) {
                    out.insert(format!("coding {system}|{code}"));
                } else if let (Some(system), Some(value)) = (
                    object.get("system").and_then(Value::as_str),
                    object.get("value").and_then(Value::as_str),
                ) {
                    out.insert(format!("identifier {system}|{value}"));
                }
                if let Some(number) = object.get("value").filter(|v| v.is_number()) {
                    out.insert(format!("quantity {number}"));
                }
                for (child_key, child) in object {
                    if matches!(
                        child_key.as_str(),
                        "text" | "reference" | "id" | "meta" | "fullUrl" | "display" | "extension"
                    ) {
                        continue;
                    }
                    walk(child, child_key, out);
                }
            }
            Value::Array(items) => {
                for item in items {
                    walk(item, key, out);
                }
            }
            Value::String(text) => {
                let date_like = text.len() >= 4
                    && text.as_bytes()[..4].iter().all(u8::is_ascii_digit)
                    && (text.len() == 4 || text.as_bytes()[4] == b'-');
                if date_like {
                    out.insert(format!("date {}", text.split('T').next().unwrap_or(text)));
                } else if matches!(
                    key,
                    "status"
                        | "intent"
                        | "category"
                        | "gender"
                        | "type"
                        | "criticality"
                        | "severity"
                        | "use"
                ) {
                    out.insert(format!("{key} {text}"));
                }
            }
            Value::Bool(b) if key != "userSelected" => {
                out.insert(format!("{key} {b}"));
            }
            _ => {}
        }
    }
    let mut out = std::collections::BTreeSet::new();
    walk(resource, "", &mut out);
    out
}

/// The consensus comparison in Markdown.
pub fn consensus_markdown(results: &[ConsensusResult]) -> String {
    use std::fmt::Write;
    let mut out = String::new();
    let (facts, matched): (usize, usize) = results
        .iter()
        .fold((0, 0), |(f, m), r| (f + r.facts, m + r.matched));
    let _ = writeln!(
        out,
        "## Agreement with the C-CDA on FHIR consensus outputs\n"
    );
    let _ = writeln!(
        out,
        "Values of the recommended resources (`mappings/examples/CDAtoFHIRExamples/Rec_Output`) our conversion of the shared input has: **{matched} of {facts} ({})**. The `_draft` outputs are drafts: where they differ from the mapping tables (SNOMED CT as `http://www.snomed.org/`, a note's category as a LOINC part, `34109-9` kept in its type) the tables are followed.\n",
        percent(matched, facts)
    );
    let _ = writeln!(
        out,
        "| Recommended | Type | Values | Ours | Missing |\n|---|---|---|---|---|"
    );
    for result in results {
        let missing: Vec<String> = result
            .missing
            .iter()
            .take(6)
            .map(|m| format!("`{m}`"))
            .collect();
        let _ = writeln!(
            out,
            "| {} | {} | {} | {} | {} |",
            result.file,
            result.resource_type,
            result.facts,
            result.matched,
            missing.join(", ")
        );
    }
    out
}
